package com.trendscout.core.ideas

/**
 * Offline, rule-based generator used when no AI key is configured or the AI service is unavailable.
 * It produces structural scaffolds from the trend's real data; creative details are left to the author.
 */
object TemplateIdeaGenerator {

    private data class Pattern(val title: String, val concept: String, val hook: String, val climax: String, val loop: String)

    private fun patterns(g: Genre, trend: String, speech: Boolean): List<Pattern> {
        val say = if (speech) "одной короткой фразой" else "текстом на экране"
        return when (g) {
            Genre.VISUAL_HUMOR -> listOf(
                Pattern("Буквальное прочтение", "Механику «$trend» показать буквально: обычная бытовая ситуация, где приём тренда понят слишком прямо.", "Крупный план предмета, который вот-вот поведёт себя странно; подпись $say задаёт ожидание.", "Предмет/герой выполняет приём тренда в самом неуместном месте.", "Последний кадр совпадает с первым — предмет возвращается в исходное положение."),
                Pattern("Масштаб наоборот", "Перенести «$trend» в мини-масштаб (игрушки, еда, канцелярия) — те же шаги, другой мир.", "Макросъёмка: зритель 1–2 секунды не понимает размер объекта.", "Отъезд камеры показывает реальный масштаб.", "Камера снова «въезжает» в мини-мир — начало ролика."),
            )
            Genre.ABSURD -> listOf(
                Pattern("Логика сна", "Каждый шаг «$trend» выполняется правильно, но последствия абсурдны и нарастают.", "Первый же кадр нарушает одно правило реальности без объяснений.", "Абсурд достигает предела — весь кадр подчиняется правилу тренда.", "Герой просыпается в кадре, с которого всё началось."),
                Pattern("Серьёзно о нелепом", "Подать «$trend» как строгую инструкцию/документалку с нелепым содержанием.", "Строгий титр $say + совершенно нелепое изображение.", "Инструкция «срабатывает» с неожиданным масштабом.", "Титр «Шаг 1» снова появляется в финале."),
            )
            Genre.TWIST_ENDING -> listOf(
                Pattern("Ложное ожидание", "Сыграть «$trend» по канону 80% ролика, затем сменить роль героя.", "Знакомое начало тренда — зритель узнаёт и ждёт привычный финал.", "Резкий поворот: оказывается, всё снимал/делал другой персонаж.", "Поворот объясняет первый кадр — при повторе он читается иначе."),
                Pattern("Смена точки зрения", "Тот же тренд глазами предмета/питомца/зрителя.", "Нестандартный ракурс без объяснения.", "Раскрытие, чей это взгляд.", "Возврат к ракурсу первого кадра."),
            )
            Genre.REACTION -> listOf(
                Pattern("Реакция на неожиданную деталь", "Реакция не на сам тренд, а на маленькую деталь внутри него, которую никто не замечает.", "Стоп-кадр с обведённой деталью $say.", "Деталь оказывается важнее основного действия.", "Возврат к стоп-кадру с той же обводкой."),
                Pattern("Эксперт вне контекста", "Реакция «специалиста» из совершенно другой области на «$trend».", "Подпись с «профессией» реагирующего.", "Профессиональный разбор доходит до нелепого вывода.", "Реагирующий начинает смотреть ролик заново."),
            )
            Genre.ANIMATION -> listOf(
                Pattern("Стоп-моушен", "Повторить механику «$trend» в стоп-моушене из бытовых предметов.", "Предмет «оживает» с первого кадра.", "Самый сложный шаг тренда в анимации.", "Предметы возвращаются на свои места."),
                Pattern("Рисованный слой", "Живое видео + рисованные элементы, которые выполняют тренд вместо героя.", "Нарисованный персонаж появляется поверх реального кадра.", "Персонаж «ломает» реальный объект.", "Персонаж стирает себя — пустой кадр как в начале."),
            )
            Genre.MINI_STORY -> listOf(
                Pattern("История за 3 акта", "Завязка — конфликт — развязка, где приём «$trend» решает конфликт.", "Конфликт показан сразу, без вступления.", "Решение через приём тренда.", "Последняя реплика/кадр запускает ту же историю заново."),
                Pattern("До и после", "Одна и та же ситуация «до» и «после» тренда.", "Кадр «после» в первые 2 секунды как интрига.", "Переход «до → после» на бит звука.", "Финальный кадр «после» = первый кадр ролика."),
            )
            Genre.EXPERIMENT -> listOf(
                Pattern("Проверка тренда", "Проверить, работает ли «$trend» в необычных условиях (на холоде, с ребёнком, на работе).", "Вопрос-гипотеза $say + таймер.", "Неожиданный результат эксперимента.", "Таймер снова на нуле — «попытка №2»."),
                Pattern("Один параметр", "Повторить тренд несколько раз, меняя один параметр.", "Сетка 2×2 вариантов, зритель выбирает фаворита.", "Последний вариант — самый неожиданный.", "Возврат к сетке."),
            )
            Genre.PARODY -> listOf(
                Pattern("Пародия на жанр", "Снять «$trend» в стилистике другого жанра (нуар, реклама 90-х, природа).", "Узнаваемый стилистический штамп жанра.", "Штамп жанра и тренда сталкиваются.", "Заставка жанра повторяется."),
                Pattern("Слишком старательно", "Персонаж готовится к тренду как к олимпиаде.", "Разминка/подготовка с серьёзным лицом.", "Сам тренд длится одну секунду.", "Персонаж снова начинает разминку."),
            )
            Genre.NO_WORDS -> listOf(
                Pattern("Чистый визуал", "Механика «$trend» без слов: понятна в любой стране только через действие и монтаж.", "Сильное движение в кадре в первые полсекунды.", "Визуальный трюк/переход на сильную долю звука.", "Движение финала зеркально стартовому."),
                Pattern("Ритм-монтаж", "Склейки строго в такт: каждый шаг тренда на бит.", "Первый бит совпадает с резким действием.", "Ускорение ритма склеек.", "Последняя склейка ведёт в первый кадр."),
            )
        }
    }

    fun generate(req: IdeaRequest): List<Idea> {
        val d = req.durationSec.coerceIn(5, 180)
        val hookEnd = 2
        val buildUp = (d * 0.6).toInt().coerceAtLeast(hookEnd + 1)
        val climaxEnd = (d * 0.85).toInt().coerceIn(buildUp + 1, d)
        val tags = req.brief.hashtags.take(5).joinToString(" ") { "#$it" }
        val sounds = req.brief.sounds.take(3).joinToString(", ")
        val notes = buildString {
            if (sounds.isNotEmpty()) append("Звуки из данных: $sounds. ") else append("Звук: нет данных о связанных звуках. ")
            if (tags.isNotEmpty()) append("Хештеги из данных: $tags.") else append("Хештеги: нет данных.")
        }
        val tips = buildList {
            add("Первая склейка — не позже 1,5 с.")
            if (!req.speech) add("Весь смысл — в изображении и тексте на экране; субтитры не нужны.") else add("Добавьте субтитры: многие смотрят без звука.")
            when (req.complexity) {
                Complexity.LOW -> add("Снимайте одним дублем на телефон, монтаж — 3–5 склеек.")
                Complexity.MEDIUM -> add("Заранее раскадруйте 6–10 планов, держите единый свет.")
                Complexity.HIGH -> add("Планируйте эффекты до съёмки, снимайте запасные дубли кульминации.")
            }
            add("Финальный кадр подгоните под первый для бесшовного повтора.")
        }
        val adaptation = "Для ${req.targetCountryName}: замените бытовые детали и надписи на местные реалии, проверьте, не завязан ли юмор на язык; " +
            "актуальность звуков и хештегов в этой стране проверьте в TikTok Creative Center для региона ${req.targetCountry}."
        return patterns(req.genre, req.brief.name, req.speech).take(req.count.coerceAtLeast(1)).map { p ->
            Idea(
                title = p.title,
                concept = p.concept,
                script = listOf(
                    Beat(0, hookEnd, p.hook),
                    Beat(hookEnd, buildUp, "Развитие: показываем механику тренда, нарастание."),
                    Beat(buildUp, climaxEnd, p.climax),
                    Beat(climaxEnd, d, p.loop),
                ),
                hook = p.hook,
                climax = p.climax,
                loopEnding = p.loop,
                editingTips = tips,
                soundAndTagNotes = notes,
                adaptation = adaptation,
                origin = IdeaOrigin.TEMPLATE,
            )
        }
    }
}
